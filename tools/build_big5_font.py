"""Generate web/font_big5.js: 16x16 bitmaps of the Traditional Chinese characters of Big5 (rows A1-F9), taken from GNU Unifont's "T source" build
(ref/unifont/unifont_t-18.0.01.bdf.gz, downloaded from https://unifoundry.com/unifont/, SIL OFL 1.1 / GPLv2+ with the font embedding exception, see NOTICE.md).
Why: a Big5 program's Chinese text used to be drawn from whatever system font the browser had, and thin vector fonts lose strokes at 16 px.
Only characters that the font draws as a full 16 x 16 cell go in (symbols that Unifont draws 8 wide still come from the system font).
Usage: python tools/build_big5_font.py [path to the .bdf.gz]"""
import base64, gzip, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "ref", "unifont", "unifont_t-18.0.01.bdf.gz")

glyphs, code, bbx, rows = {}, None, None, None
with gzip.open(SRC, "rt", encoding="utf-8") as f:
    for line in f:
        line = line.strip()
        if line.startswith("ENCODING"): code = int(line.split()[1])
        elif line.startswith("BBX"): bbx = tuple(int(v) for v in line.split()[1:5])
        elif line == "BITMAP": rows = []
        elif line == "ENDCHAR":
            if code is not None and code >= 0 and bbx == (16, 16, 0, -2) and len(rows) == 16: glyphs[code] = bytes.fromhex("".join(rows))
            code, rows = None, None
        elif rows is not None: rows.append(line)

chars, bits = [], bytearray()
for lead in range(0xA1, 0xFA):                                   # the order of the Big5 codes, so the file is stable
    for trail in list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)):
        try: ch = bytes([lead, trail]).decode("cp950")
        except UnicodeDecodeError: continue
        if len(ch) != 1 or 0xE000 <= ord(ch) <= 0xF8FF or ord(ch) not in glyphs or ch in chars: continue
        chars.append(ch); bits += glyphs[ord(ch)]

out = os.path.join(ROOT, "web", "font_big5.js")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// generated by tools/build_big5_font.py from GNU Unifont 18.0.01 (T source, SIL OFL 1.1 / GPLv2+ with the font embedding exception, see NOTICE.md) - do not edit\n"
            "// 16x16 Traditional Chinese characters of Big5: chars = the characters, bits = 32 bytes per character in the same order (rows of 2 bytes, leftmost pixel = top bit); read by web/lcdfont.js\n"
            "var GVB_BIG5FONT = {chars: \"" + "".join(chars) + "\", bits: \"" + base64.b64encode(bytes(bits)).decode("ascii") + "\"};\n"
            "if (typeof module !== 'undefined') module.exports = GVB_BIG5FONT;\n")
print("wrote web/font_big5.js:", len(chars), "characters,", os.path.getsize(out), "bytes")
